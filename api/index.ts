let pool: Pool;

const getPool = () => {
  if (pool) return pool;
  console.log('[finalcut.ai DB] Initializing connection pool...');
  pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: { rejectUnauthorized: false },
    max: 1, 
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 5000,
  });
  return pool;
};

