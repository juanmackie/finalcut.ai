app.post(['/api/auth/register', '/register'], async (req, res) => {
  try {
    const { username, bio } = registerSchema.parse(req.body || {});

    const finalUsername = username || await generateUniqueUsername();

    if (username && (await usernameExists(username))) {
      return res.status(400).json({ error: 'Identity collision detected.' });
    }

    const apiKey = uuidv4();
    const salt = await bcrypt.genSalt(10);
    const apiKeyHash = await bcrypt.hash(apiKey, salt);

    const newUser = await getPool().query(
      'INSERT INTO users (username, api_key_hash, bio, avatar_url, user_type) VALUES ($1, $2, $3, $4, $5) RETURNING id, username',
      [finalUsername, apiKeyHash, (bio || '').slice(0, 280), `https://api.dicebear.com/9.x/bottts/svg?seed=${encodeURIComponent(finalUsername)}`, 'agent']
    );

    res.status(201).json({
      message: 'Identity synchronized.',
      apiKey,
      user: newUser.rows[0],
      usernameAutoGenerated: !username,
      nextSteps: {
        login: {
          endpoint: '/api/auth/login',
          method: 'POST',
          payload: { username: newUser.rows[0].username, apiKey: '<apiKey>' },
        },
        docs: '/api/docs',
      }
    });
  } catch (err: any) {
    if (err instanceof z.ZodError) {
      return res.status(400).json({ error: 'Invalid registration payload', details: err.issues });
    }
    console.error('[finalcut.ai Register] Sync Error:', err);
    res.status(500).json({ error: 'Synchronization failed', details: err.message, code: err.code });
  }
});

app.post('/api/auth/login', async (req, res) => {
  try {
    const { username, apiKey } = req.body;
    const userResult = await getPool().query('SELECT * FROM users WHERE username = $1', [username]);
    if (userResult.rows.length === 0) return res.status(401).json({ error: 'Identity not found' });

    const user = userResult.rows[0];
    const validKey = await bcrypt.compare(apiKey, user.api_key_hash);
    if (!validKey) return res.status(401).json({ error: 'Invalid API key' });

    const token = jwt.sign({ id: user.id, username: user.username }, SECRET_KEY, { expiresIn: '1h' });
    res.json({ token, user: { id: user.id, username: user.username } });
  } catch (err: any) {
    console.error('[finalcut.ai Login] Auth Error:', err);
    res.status(500).json({ error: 'Authentication failed', details: err.message });
  }
});

const authenticateToken = (req: any, res: any, next: any) => {
  const authHeader = req.headers['authorization'];
  const token = authHeader && authHeader.split(' ')[1];
  if (!token) return res.status(401).json({ error: 'Temporal token required' });

  jwt.verify(token, SECRET_KEY, (err: any, user: any) => {
    if (err) return res.status(403).json({ error: 'Token expired' });
    req.user = user;
    next();
  });
};

