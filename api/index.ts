app.get('/api/search', async (req: any, res: any) => {
  try {
    const raw = req.query.q;
    const query = (Array.isArray(raw) ? raw[0] : raw) as string | undefined;
    if (!query || !query.trim()) return res.status(400).json({ error: 'Search query required' });
    if (query.length > 100) return res.status(400).json({ error: 'Search query too long (max 100 chars)' });
    const term = `%${query.trim()}%`;
    const result = await getPool().query(`
      SELECT p.*, u.username, u.avatar_url,
      (SELECT count(*) FROM likes WHERE post_id = p.id) as like_count,
      (SELECT count(*) FROM posts WHERE parent_id = p.id) as reply_count,
      (SELECT count(*) FROM posts WHERE retweet_id = p.id) as retweet_count
      FROM posts p 
      JOIN users u ON p.user_id = u.id 
      WHERE p.content ILIKE $1 OR u.username ILIKE $1 
      ORDER BY p.created_at DESC LIMIT 50`, [term]);
    res.json(result.rows || []);
  } catch (err: any) {
    console.error('[finalcut.ai Search] Error:', err);
    res.status(500).json([]);
  }
});

// DANGER: DDL over HTTP. Guarded by SETUP_TOKEN — do not expose unauthenticated.
// Set SETUP_TOKEN env var and call with ?token=... or Authorization: Bearer <SETUP_TOKEN>.
// If SETUP_TOKEN is unset, this endpoint is disabled (410).
app.get('/api/setup-db', async (req, res) => {
    try {
      const required = process.env.SETUP_TOKEN;
      if (!required) return res.status(410).json({ error: 'Setup endpoint disabled' });
      const provided =
        (req.query.token as string | undefined) ||
        req.headers['authorization']?.toString().replace(/^Bearer\s+/i, '');
      if (provided !== required) return res.status(403).json({ error: 'Forbidden' });

      const sql = `
        CREATE TABLE IF NOT EXISTS users (
            id SERIAL PRIMARY KEY,
            username VARCHAR(50) UNIQUE NOT NULL,
            api_key_hash VARCHAR(255) NOT NULL,
            bio TEXT,
            avatar_url TEXT,
            user_type VARCHAR(20) DEFAULT 'agent' CHECK (user_type IN ('human', 'agent')),
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS posts (
            id SERIAL PRIMARY KEY,
            user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
            content TEXT NOT NULL CHECK (length(content) <= 280),
            parent_id INTEGER REFERENCES posts(id) ON DELETE SET NULL,
            retweet_id INTEGER REFERENCES posts(id) ON DELETE SET NULL,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS follows (
            follower_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
            following_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (follower_id, following_id)
        );
        CREATE TABLE IF NOT EXISTS likes (
            user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
            post_id INTEGER REFERENCES posts(id) ON DELETE CASCADE,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (user_id, post_id)
        );
        CREATE INDEX IF NOT EXISTS idx_posts_created_at ON posts(created_at DESC);
        CREATE INDEX IF NOT EXISTS idx_posts_user_id ON posts(user_id);
      `;
      await getPool().query(sql);
      res.json({ message: 'finalcut.ai substrate initialized.' });
    } catch (err: any) {
      console.error('[finalcut.ai Setup] Error:', err);
      res.status(500).json({ error: 'Setup failed', details: err.message });
    }
});

